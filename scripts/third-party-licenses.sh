#!/bin/bash
# Collects the license files of every Go module linked into withalbum-server
# (all release targets) and of the Go standard library into
# third_party/go-modules/, which release archives include.
#
#   bash scripts/third-party-licenses.sh          # regenerate
#   bash scripts/third-party-licenses.sh --check  # fail if out of date
#
# Run it after any go.mod change. Non-Go material (the SEED Design tokens,
# Apache-2.0) lives in third_party/seed-design/ and is not touched here.
set -euo pipefail
cd "$(dirname "$0")/.."

CHECK=0
case "${1:-}" in
  --check) CHECK=1 ;;
  "") ;;
  *) echo "Usage: bash scripts/third-party-licenses.sh [--check]" >&2; exit 2 ;;
esac

DEST=third_party/go-modules
# Keep in sync with the build targets of .goreleaser.yaml.
TARGETS="darwin/arm64 darwin/amd64 linux/amd64 linux/arm64 linux/arm"

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT
OUT="$WORK/go-modules"
mkdir -p "$OUT"

go mod download
mods="$(for t in $TARGETS; do
  GOOS="${t%/*}" GOARCH="${t#*/}" GOARM=7 CGO_ENABLED=0 \
    go list -deps -f '{{with .Module}}{{if not .Main}}{{.Path}} {{.Version}}{{end}}{{end}}' ./server
done | sort -u)"

{
  echo "# Go modules linked into withalbum-server (release targets: $TARGETS)."
  echo "# Generated by scripts/third-party-licenses.sh; do not edit."
  echo "go (standard library)"
  printf '%s\n' "$mods"
} > "$OUT/MODULES.txt"

copy_licenses() { # <source dir> <dest dir>
  local found=0 f
  mkdir -p "$2"
  for f in "$1"/*; do
    [[ -f "$f" ]] || continue
    case "$(basename "$f" | tr '[:lower:]' '[:upper:]')" in
      LICENSE*|LICENCE*|COPYING*|NOTICE*|PATENTS*|AUTHORS*)
        cp "$f" "$2/"; chmod 0644 "$2/$(basename "$f")"; found=1 ;;
    esac
  done
  [[ $found == 1 ]] || { echo "no license file found in $1" >&2; exit 1; }
}

while read -r path version; do
  [[ -n "$path" ]] || continue
  dir="$(go list -m -f '{{.Dir}}' "$path")"
  [[ -n "$dir" && -d "$dir" ]] || { echo "module $path $version is not in the module cache" >&2; exit 1; }
  copy_licenses "$dir" "$OUT/$path"
done <<< "$mods"

# The Go standard library (compiled into every binary).
goroot="$(go env GOROOT)"
golicense=""
for f in "$goroot/LICENSE" "$goroot/../LICENSE"; do
  if [[ -f "$f" ]]; then golicense="$f"; break; fi
done
[[ -n "$golicense" ]] || { echo "Go LICENSE not found next to GOROOT $goroot" >&2; exit 1; }
mkdir -p "$OUT/go"
cp "$golicense" "$OUT/go/LICENSE"
chmod 0644 "$OUT/go/LICENSE"

if [[ $CHECK == 1 ]]; then
  if ! diff -r "$DEST" "$OUT" >/dev/null 2>&1; then
    diff -r "$DEST" "$OUT" || true
    echo "third_party/go-modules is out of date: run bash scripts/third-party-licenses.sh" >&2
    exit 1
  fi
  echo "third_party/go-modules is up to date ($(grep -vc '^#' "$OUT/MODULES.txt") entries)"
  exit 0
fi
rm -rf "$DEST"
mkdir -p "$(dirname "$DEST")"
cp -R "$OUT" "$DEST"
echo "wrote $DEST ($(grep -vc '^#' "$DEST/MODULES.txt") entries)"
