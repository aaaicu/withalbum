// Package tlsid manages the server's self-signed TLS identity.
//
// The server creates its own key pair on the first start with TLS and keeps
// it in <root>/.system/tls/server.pem: the PKCS#8 ECDSA P-256 private key
// and the certificate in one file, mode 0600, written to a temp file, synced
// and renamed into place, so a crash leaves either no identity or a complete
// one.
//
// Clients do not trust the certificate through a CA. They pin the SHA-256
// of the certificate's SubjectPublicKeyInfo (SPKI), which an administrator
// reads at the server console or in the dashboard and transfers to a device
// (QR payload, see PairingPayload). The pin stays valid as long as the key
// does: when the certificate nears its end of validity, or lacks a host name
// the server is told to listen on, it is re-issued with the same key, so
// paired devices keep working. A new key (and thus re-pairing every device)
// is only made when no identity exists.
//
// The private key is never logged or printed; only fingerprints are.
package tlsid

import (
	"bytes"
	"crypto/ecdsa"
	"crypto/elliptic"
	"crypto/rand"
	"crypto/sha256"
	"crypto/tls"
	"crypto/x509"
	"crypto/x509/pkix"
	"encoding/base64"
	"encoding/hex"
	"encoding/pem"
	"errors"
	"fmt"
	"math/big"
	"net"
	"net/url"
	"os"
	"path/filepath"
	"slices"
	"strings"
	"time"

	"github.com/aaaicu/withalbum/internal/storage"
)

const (
	// DirName is the directory under .system that holds the identity.
	DirName = "tls"
	// FileName holds key and certificate (PEM).
	FileName = "server.pem"

	// Validity of an issued certificate. Apple platforms reject server
	// certificates valid for more than 825 days, so stay below that.
	Validity = 820 * 24 * time.Hour
	// RenewBefore: a certificate expiring within this period is re-issued
	// (same key) at startup.
	RenewBefore = 60 * 24 * time.Hour
)

var (
	// ErrNotFound: no identity exists yet (Load only).
	ErrNotFound = errors.New("no TLS identity")
	// ErrInsecureFile: the identity file is not a regular file private to
	// its owner (mode must not grant any group or other access).
	ErrInsecureFile = errors.New("TLS identity file is not private (want a regular file with mode 0600)")
	// ErrInvalid: the identity file cannot be parsed or its key does not
	// match its certificate.
	ErrInvalid = errors.New("TLS identity file is invalid")
)

// Path returns the identity file of a storage root.
func Path(root string) string { return filepath.Join(root, ".system", DirName, FileName) }

// Identity is a loaded key pair.
type Identity struct {
	Certificate tls.Certificate
	Leaf        *x509.Certificate
	// SPKISHA256 is the pin: SHA-256 of the SubjectPublicKeyInfo.
	SPKISHA256 [32]byte
	// CertSHA256 is the SHA-256 of the DER certificate (what browsers show).
	CertSHA256 [32]byte
	// Created: a new key was generated by this call. Renewed: the
	// certificate was re-issued with the existing key.
	Created, Renewed bool
}

// SPKIHex is the pin as 64 lower-case hex digits.
func (id *Identity) SPKIHex() string { return hex.EncodeToString(id.SPKISHA256[:]) }

// SPKIBase64 is the pin in standard base64 (curl --pinnedpubkey sha256//...).
func (id *Identity) SPKIBase64() string { return base64.StdEncoding.EncodeToString(id.SPKISHA256[:]) }

// CertHex is the certificate fingerprint as 64 lower-case hex digits.
func (id *Identity) CertHex() string { return hex.EncodeToString(id.CertSHA256[:]) }

// Colons formats a hex fingerprint as AB:CD:... for reading aloud.
func Colons(h string) string {
	var b strings.Builder
	for i := 0; i+1 < len(h); i += 2 {
		if i > 0 {
			b.WriteByte(':')
		}
		b.WriteString(strings.ToUpper(h[i : i+2]))
	}
	return b.String()
}

// PairingPayload is the text a device scans (QR) or receives to connect:
// withalbum://pair?v=1&url=<server URL>&spki_sha256=<hex pin>.
func PairingPayload(serverURL, spkiHex string) string {
	return PairingPayloadRelay(serverURL, spkiHex, "", "")
}

// PairingPayloadRelay is PairingPayload with the relay through which the
// server is also reachable (docs/RELAY_DESIGN.md): relay=<host:port> and
// rid=<rendezvous ID> are added when relayAddr is not empty. The version
// stays 1: the fields are optional, and apps that do not know them ignore
// them (they still pin the same key).
func PairingPayloadRelay(serverURL, spkiHex, relayAddr, rid string) string {
	q := url.Values{"v": {"1"}, "url": {serverURL}, "spki_sha256": {spkiHex}}
	if relayAddr != "" {
		q.Set("relay", relayAddr)
		q.Set("rid", rid)
	}
	return "withalbum://pair?" + q.Encode()
}

// ServerConfig is the TLS configuration of the server: TLS 1.3 only (its
// cipher suites are all AEAD with forward secrecy), the identity's
// certificate, no client certificates.
func ServerConfig(id *Identity) *tls.Config {
	return &tls.Config{MinVersion: tls.VersionTLS13, Certificates: []tls.Certificate{id.Certificate}}
}

// PinnedClientConfig is a client configuration that accepts exactly the
// server whose SPKI SHA-256 is pin, whatever host name or CA it presents.
// It shows how a client connects with a pin and is used by tests.
func PinnedClientConfig(pin [32]byte) *tls.Config {
	return &tls.Config{
		MinVersion: tls.VersionTLS13,
		// The CA chain and host name are not what is trusted here; the pin
		// is, and it is checked below on every handshake.
		InsecureSkipVerify: true,
		VerifyConnection: func(cs tls.ConnectionState) error {
			if len(cs.PeerCertificates) == 0 {
				return errors.New("tls pin: no server certificate")
			}
			got := sha256.Sum256(cs.PeerCertificates[0].RawSubjectPublicKeyInfo)
			if got != pin {
				return errors.New("tls pin: server key does not match the paired fingerprint")
			}
			return nil
		},
	}
}

// DefaultHosts are always in the certificate.
var DefaultHosts = []string{"localhost", "127.0.0.1", "::1"}

// Load reads the identity of root without creating or changing anything.
func Load(root string) (*Identity, error) {
	b, err := readPrivate(Path(root))
	if err != nil {
		return nil, err
	}
	return parse(b)
}

// LoadOrCreate returns the identity of root, creating .system/tls and a new
// key pair if none exists, and re-issuing the certificate with the same key
// if it expires within RenewBefore (or has expired) or lacks one of hosts
// (DNS names or IP addresses). The volume must already be verified.
func LoadOrCreate(root string, hosts []string, now time.Time) (*Identity, error) {
	path := Path(root)
	b, err := readPrivate(path)
	if errors.Is(err, ErrNotFound) {
		if err := storage.MkdirIn(filepath.Dir(path)); err != nil {
			return nil, fmt.Errorf("tls: create %s: %w", filepath.Dir(path), err)
		}
		key, err := ecdsa.GenerateKey(elliptic.P256(), rand.Reader)
		if err != nil {
			return nil, fmt.Errorf("tls: generate key: %w", err)
		}
		id, err := issue(path, key, hosts, now)
		if err != nil {
			return nil, err
		}
		id.Created = true
		return id, nil
	}
	if err != nil {
		return nil, err
	}
	id, err := parse(b)
	if err != nil {
		return nil, err
	}
	if !needsRenewal(id.Leaf, hosts, now) {
		return id, nil
	}
	key, ok := id.Certificate.PrivateKey.(*ecdsa.PrivateKey)
	if !ok {
		return nil, fmt.Errorf("%w: unsupported key type %T", ErrInvalid, id.Certificate.PrivateKey)
	}
	renewed, err := issue(path, key, unionHosts(id.Leaf, hosts), now)
	if err != nil {
		return nil, err
	}
	renewed.Renewed = true
	return renewed, nil
}

// readPrivate reads the identity file after checking it is a regular file
// (not a symlink) without group or other permissions.
func readPrivate(path string) ([]byte, error) {
	fi, err := os.Lstat(path)
	if errors.Is(err, os.ErrNotExist) {
		return nil, ErrNotFound
	}
	if err != nil {
		return nil, fmt.Errorf("tls: %w", err)
	}
	if !fi.Mode().IsRegular() || fi.Mode().Perm()&0o077 != 0 {
		return nil, fmt.Errorf("%w: %s has mode %v", ErrInsecureFile, path, fi.Mode())
	}
	b, err := os.ReadFile(path)
	if err != nil {
		return nil, fmt.Errorf("tls: %w", err)
	}
	return b, nil
}

func parse(b []byte) (*Identity, error) {
	cert, err := tls.X509KeyPair(b, b)
	if err != nil {
		// The error of X509KeyPair never contains key material.
		return nil, fmt.Errorf("%w: %v", ErrInvalid, err)
	}
	if len(cert.Certificate) != 1 || cert.Leaf == nil {
		return nil, fmt.Errorf("%w: want exactly one certificate", ErrInvalid)
	}
	id := &Identity{Certificate: cert, Leaf: cert.Leaf}
	id.SPKISHA256 = sha256.Sum256(cert.Leaf.RawSubjectPublicKeyInfo)
	id.CertSHA256 = sha256.Sum256(cert.Leaf.Raw)
	return id, nil
}

func needsRenewal(leaf *x509.Certificate, hosts []string, now time.Time) bool {
	if now.Add(RenewBefore).After(leaf.NotAfter) || now.Before(leaf.NotBefore) {
		return true
	}
	for _, h := range hosts {
		if ip := net.ParseIP(h); ip != nil {
			if !slices.ContainsFunc(leaf.IPAddresses, ip.Equal) {
				return true
			}
		} else if !slices.Contains(leaf.DNSNames, h) {
			return true
		}
	}
	return false
}

func unionHosts(leaf *x509.Certificate, hosts []string) []string {
	out := slices.Clone(leaf.DNSNames)
	for _, ip := range leaf.IPAddresses {
		out = append(out, ip.String())
	}
	return append(out, hosts...)
}

// issue creates a certificate for key and atomically replaces path with key
// and certificate.
func issue(path string, key *ecdsa.PrivateKey, hosts []string, now time.Time) (*Identity, error) {
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
	if err != nil {
		return nil, fmt.Errorf("tls: serial: %w", err)
	}
	tmpl := &x509.Certificate{
		SerialNumber:          serial,
		Subject:               pkix.Name{CommonName: "WithAlbum server", Organization: []string{"WithAlbum self-hosted"}},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(Validity),
		KeyUsage:              x509.KeyUsageDigitalSignature,
		ExtKeyUsage:           []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
		BasicConstraintsValid: true,
	}
	for _, h := range append(slices.Clone(DefaultHosts), hosts...) {
		if h == "" {
			continue
		}
		if ip := net.ParseIP(h); ip != nil {
			if ip.IsUnspecified() || slices.ContainsFunc(tmpl.IPAddresses, ip.Equal) {
				continue
			}
			tmpl.IPAddresses = append(tmpl.IPAddresses, ip)
		} else if !slices.Contains(tmpl.DNSNames, h) {
			tmpl.DNSNames = append(tmpl.DNSNames, h)
		}
	}
	der, err := x509.CreateCertificate(rand.Reader, tmpl, tmpl, &key.PublicKey, key)
	if err != nil {
		return nil, fmt.Errorf("tls: create certificate: %w", err)
	}
	pkcs8, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, fmt.Errorf("tls: encode key: %w", err)
	}
	var buf bytes.Buffer
	_ = pem.Encode(&buf, &pem.Block{Type: "PRIVATE KEY", Bytes: pkcs8})
	_ = pem.Encode(&buf, &pem.Block{Type: "CERTIFICATE", Bytes: der})
	if err := writeAtomic(path, buf.Bytes()); err != nil {
		return nil, err
	}
	return parse(buf.Bytes())
}

// writeAtomic writes b to a 0600 temp file next to path, syncs it, renames
// it over path and syncs the directory.
func writeAtomic(path string, b []byte) error {
	dir := filepath.Dir(path)
	f, err := os.CreateTemp(dir, ".server-*.tmp")
	if err != nil {
		return fmt.Errorf("tls: %w", err)
	}
	tmp := f.Name()
	defer os.Remove(tmp)
	if err := f.Chmod(0o600); err != nil {
		f.Close()
		return fmt.Errorf("tls: %w", err)
	}
	if _, err := f.Write(b); err != nil {
		f.Close()
		return fmt.Errorf("tls: write identity: %w", err)
	}
	if err := f.Sync(); err != nil {
		f.Close()
		return fmt.Errorf("tls: sync identity: %w", err)
	}
	if err := f.Close(); err != nil {
		return fmt.Errorf("tls: %w", err)
	}
	if err := os.Rename(tmp, path); err != nil {
		return fmt.Errorf("tls: %w", err)
	}
	return storage.SyncDir(dir)
}
